const RETIRED_BATTER_RESULTS = new Set(['GO', 'FO', 'LO', 'DP', 'TP'])

// Direction bands, in degrees off dead centre, positive toward the first-base
// side. The infield and outfield get different vocabularies because "toward
// shortstop" and "toward left-center" describe the same direction at different
// depths, and a ground ball that is called a fly ball's destination reads as a
// tracker error to anyone checking it.
const OUTFIELD_ZONES = [
  [-90, -37.5, 'the left-field line'],
  [-37.5, -26, 'left field'],
  [-26, -14, 'left-center'],
  [-14, 14, 'center field'],
  [14, 26, 'right-center'],
  [26, 37.5, 'right field'],
  [37.5, 90, 'the right-field line'],
]

const INFIELD_ZONES = [
  [-90, -30, 'third base'],
  [-30, -9, 'shortstop'],
  [-9, 9, 'the pitcher'],
  [9, 30, 'second base'],
  [30, 90, 'first base'],
]

// How far out a ball has to finish before the outfield vocabulary describes it.
// "Toward the left-field line" for a ball that stopped sixteen feet in front of
// the plate is not a rounding error, it is a different play.
const INFIELD_ZONE_MAX_FEET = 120

function zoneFor(angleDeg, trajectory, distanceFeet = null) {
  if (!Number.isFinite(angleDeg)) return null
  // The trajectory letter decides it when there is one. When there is not --
  // an unclassified ball, or a foul, which the tracker never classifies -- the
  // measured distance decides instead of defaulting to the outfield, which is
  // how a bunt ended up described as a ball down the left-field line.
  const infield = (trajectory === 'G' || trajectory === 'B')
    || (!trajectory && Number.isFinite(distanceFeet) && distanceFeet < INFIELD_ZONE_MAX_FEET)
  const bands = infield ? INFIELD_ZONES : OUTFIELD_ZONES
  for (const [low, high, label] of bands) {
    if (angleDeg >= low && angleDeg < high) return label
  }
  return null
}

/**
 * Direction of a point in the ball's coordinate frame, in degrees off centre.
 *
 * The frame is the one parkGeometry.js documents: -Z toward centre field, +X
 * toward first base. So a positive angle is toward right field.
 */
// WHICH WAY THE TRAIN SENT IT. Jason asked for the direction beside the
// distance ("can we start including the direction it was hit in"). For a ball
// already deep in the outfield the useful direction is radial: a shove back
// toward the infield is a different play from one driven further into the
// corner, and the left/right zone alone says neither. Ten feet is the band
// where "back toward the infield" stops being a rounding error.
const TRAIN_PUSH_RADIAL_UNITS = 3.0

function trainPushDirection(from, to) {
  if (!Array.isArray(from) || !Array.isArray(to)) return null
  const before = Math.hypot(from[0], from[2])
  const after = Math.hypot(to[0], to[2])
  if (after <= before - TRAIN_PUSH_RADIAL_UNITS) return 'back toward the infield'
  if (after >= before + TRAIN_PUSH_RADIAL_UNITS) return 'further out toward the wall'
  const zone = zoneFor(directionDegrees(to), null, after * FEET_PER_UNIT)
  return zone ? `along the wall toward ${zone}` : 'along the wall'
}

export function directionDegrees(point) {
  if (!Array.isArray(point) || point.length < 3) return null
  const [x, , z] = point
  if (!Number.isFinite(x) || !Number.isFinite(z)) return null
  return (Math.atan2(x, -z) * 180) / Math.PI
}

// A foul goes outside the lines, where the fair-ball zone tables have no
// vocabulary: every one of them lands in the outermost band and comes back
// "the left-field line". The tracker's own log describes a foul by which side
// of the plate it went to, and so does this.
function foulSide(angleDeg) {
  if (!Number.isFinite(angleDeg)) return null
  if (angleDeg <= -45) return 'the third-base side'
  if (angleDeg >= 45) return 'the first-base side'
  return 'straight back'
}

function isFoulPlay(play) {
  if (!play) return false
  return play.batted_ball_class === 'foul' || play.batted_ball_class === 'foul_home_run'
}

// One definition of the scale, the same one tracker_preview_state.mjs uses.
const FEET_PER_UNIT = 3.280839895

// FEET IN THE ENGLISH, UNITS IN THE EVIDENCE. The operator reads these
// sentences and the game's unit is not something anybody watching a baseball
// game thinks in: "can we stop referring to things as units in this
// interpretation? start converting to feet." Every `evidence` payload keeps the
// measurement in the units it was measured in, so nothing downstream has to be
// re-derived to read it -- only the sentence converts.
function feet(units, digits = 1) {
  const value = Number(units)
  return Number.isFinite(value) ? (value * FEET_PER_UNIT).toFixed(digits) : null
}

// How far the ball actually finished from the plate. The at-bat's own distance
// is the right answer when the join is sound, but a play carries its own
// measurement and that is the one that has to decide the vocabulary used to
// describe THAT play.
function measuredDistanceFeet(atBat, play) {
  const units = Number(play?.landing?.distance_units)
  if (Number.isFinite(units)) return units * FEET_PER_UNIT
  const stated = Number(atBat?.hit_distance_ft)
  return Number.isFinite(stated) ? stated : null
}

function positionPhrase(position) {
  return POSITION_PHRASES[position] || (position ? `the ${position}` : 'a fielder')
}

// Sentence-initial. "the center fielder recovered the ball" reads as a
// truncated sentence, which in a QA console reads as a rendering bug.
function capitalized(phrase) {
  const text = String(phrase ?? '')
  return text ? text[0].toUpperCase() + text.slice(1) : text
}

// The character's name when the capture resolved one, and the position when it
// did not. Never a bare position code, which reads as a typo in a sentence.
// An id the 60 Hz capture could not name. Miis are not in the game's character
// table, so every one of them arrives as `char 78` and used to be narrated as
// "the first baseman" -- a sentence about a position where every other fielder
// gets a name.
const UNNAMED_CHARACTER = /^char \d+$/

// How the derivation's `impulse` reads in a sentence. Every phrase names the
// thing that arrived, because that is what was measured -- an object reaching
// the fielder on the exact frame the impulse began. `knockdown` stays vague on
// purpose: the flag marks the impact and never says what caused it, and the
// park-specific hazard clauses are the ones entitled to name that.
const KNOCKBACK_IMPULSE_PHRASE = {
  batted_ball: 'that was the force of the batted ball, taken on the frame it reached them',
  thrown_ball: 'that was the force of the throw, taken on the frame it arrived',
  knockdown: 'something floored them on that frame, and the flag does not say what',
}

// `leap` is the one impulse that is not something arriving, so it gets its own
// sentence rather than a clause hung off "was driven back". A fielder who
// catches in mid-air keeps travelling, and that follow-through passes every
// knockback test; the airborne flag on the possession frame is what says the
// jump, not the ball, is what moved them.
const LEAP_CARRY_EVIDENCE =
  'airborne on the frame they took the ball, so the drift is the jump they were already in'

// A knockback under a unit is the recoil of taking the ball, not an event, and
// the rest of the narrative already uses a one-unit floor for ball-holding
// moves.
const KNOCKBACK_NARRATIVE_FLOOR_UNITS = 1.0

/**
 * The name to print for a fielder the capture identified only by id.
 *
 * The tracker log publishes the defending side's whole alignment
 * ([TRACKER_LINEUP] fielding=P=...,C=...), and it names the Mii the way the
 * game does -- "Orange Mii (M)". So the name exists in this at-bat already;
 * it is simply on the other feed. Falling back to it beats printing a position
 * where a name belongs, and it costs nothing when the capture knew the name.
 */
function namedFielder(character, position, atBat = null) {
  if (character && !UNNAMED_CHARACTER.test(character)) return character
  const announced = position ? atBat?.fielding_alignment?.[position] : null
  return announced || null
}

function fielderPhrase(character, position, atBat = null) {
  const name = namedFielder(character, position, atBat)
  if (name) return position ? `${name} (${position})` : name
  return positionPhrase(position)
}

function actorPhrase(event, atBat = null) {
  return fielderPhrase(
    event?.character,
    event?.by || event?.thrower_position || null,
    atBat,
  )
}

class NarrativeBuilder {
  constructor() {
    this.clauses = []
    this.timeline = []
    this.counter = 0
  }

  add({ category, text, status, source, evidence = {}, t = null, frame = null }) {
    this.counter += 1
    const id = `c${String(this.counter).padStart(2, '0')}-${category}`
    this.clauses.push({
      id, category, text, status, source,
      evidence: { ...evidence, ...(t != null ? { t } : {}), ...(frame != null ? { frame } : {}) },
    })
    if (t != null || frame != null) {
      this.timeline.push({ id, category, t, frame, text })
    }
    return id
  }
}

// --- 1. contact, trajectory and location ------------------------------------

function describeContact(builder, { atBat, play }) {
  const batter = atBat.batter_name || 'The batter'
  const result = atBat.result

  if (result === 'K') {
    const type = atBat.strikeout_type
    const how = type === 'KS' ? ' swinging' : type === 'KL' ? ' looking' : ''
    builder.add({
      category: 'contact',
      text: `${batter} struck out${how}.`,
      status: type ? 'observed' : 'derived',
      source: type ? 'plate_appearance.strikeout_type' : 'plate_appearance.result',
      evidence: { result, strikeout_type: type ?? null },
    })
    return
  }
  if (result === 'BB' || result === 'HBP') {
    builder.add({
      category: 'contact',
      text: result === 'BB'
        ? `${batter} walked.`
        : `${batter} was hit by a pitch.`,
      status: 'observed',
      source: 'plate_appearance.result',
      evidence: { result },
    })
    return
  }

  const point = play?.landing?.at || play?.first_touch?.at || null
  const measuredAngle = directionDegrees(point)

  // A FOUL BALL IS NOT THIS AT-BAT'S BATTED BALL. When nothing fair joined,
  // outcomePlayFor lets a foul stand in so the page still shows the fielding it
  // does have -- but narrating it through the batted-ball path describes a ball
  // that went out of play as if it were the ball the at-bat was decided on. The
  // tracker never classifies a foul's trajectory, so that path also had no
  // letter to work with and produced "hit a ball the tracker did not classify",
  // pointed at an outfield zone, for balls that went foul near the plate.
  if (isFoulPlay(play)) {
    const side = foulSide(measuredAngle)
    const back = play.batted_ball_class === 'foul_home_run'
    builder.add({
      category: 'contact',
      text: `${batter} fouled one off${side ? ` toward ${side}` : ''}${back ? ', out of the park' : ''}.`
        + ' The tracker has no fair batted ball joined to this plate appearance,'
        + ' so what follows is the fielding on the foul, not on the ball that ended it.',
      status: 'observed',
      source: 'player_tracking_play.batted_ball_class + landing.at (ball-frame direction)',
      evidence: {
        batted_ball_class: play.batted_ball_class,
        fair_or_foul: play.fair_or_foul ?? null,
        direction_deg: Number.isFinite(measuredAngle)
          ? Math.round(measuredAngle * 10) / 10 : null,
        result,
      },
      t: 0,
      frame: play.contact_timer ?? null,
    })
    return
  }

  // The capture measures how the batter offered at the pitch; the tracker log
  // only measures how hard the ball left, which cannot tell a bunt from a
  // mishit. Where the two feeds disagree the measurement wins.
  const trajectory = (play?.contact_type === 'bunt' ? 'B' : atBat.trajectory) || null
  // An unclassified batted ball says so. "a batted ball" reads like a
  // deliberate description and hides the fact that the tracker never called
  // this one a grounder, a liner or a fly.
  const noun = TRAJECTORY_NOUNS[trajectory] || 'ball the tracker did not classify'
  const angle = Number.isFinite(measuredAngle)
    ? measuredAngle
    : (Number.isFinite(Number(atBat.hit_angle_deg)) ? Number(atBat.hit_angle_deg) : null)
  const zone = zoneFor(angle, trajectory, measuredDistanceFeet(atBat, play))

  // "deep" is a measurement, not a flourish: it is said only when a measured
  // distance says so, and the distance travels with the clause.
  const distance = Number(atBat.hit_distance_ft)
  const deep = Number.isFinite(distance) && distance >= 300 && trajectory !== 'G'
  const nounPhrase = deep && trajectory ? `a deep ${noun}` : `a ${noun}`

  if (!trajectory && !zone) {
    builder.add({
      category: 'contact',
      text: `${batter} put the ball in play. The tracker did not resolve its trajectory or direction.`,
      status: 'unknown',
      source: 'plate_appearance.trajectory + player_tracking_play.landing',
      evidence: { trajectory: null, angle_deg: null, result },
      t: play ? 0 : null,
      frame: play?.contact_timer ?? null,
    })
    return
  }

  const where = zone ? ` toward ${zone}` : ''
  builder.add({
    category: 'contact',
    text: `${batter} hit ${nounPhrase}${where}.`,
    status: Number.isFinite(measuredAngle) ? 'derived' : (zone ? 'derived' : 'observed'),
    source: Number.isFinite(measuredAngle)
      ? 'player_tracking_play.landing.at (ball-frame direction)'
      : 'plate_appearance.trajectory + plate_appearance.hit_angle_deg',
    evidence: {
      trajectory,
      trajectory_source: trajectory ? 'tracker_batted_ball' : null,
      direction_deg: angle == null ? null : Math.round(angle * 10) / 10,
      direction_source: Number.isFinite(measuredAngle)
        ? 'measured_endpoint_coordinates' : 'tracker_spray_angle',
      zone,
      hit_distance_ft: Number.isFinite(distance) ? distance : null,
      deep_threshold_ft: deep ? 300 : null,
      exit_velocity_mph: atBat.exit_velocity_mph ?? null,
      launch_angle_deg: atBat.launch_angle_deg ?? null,
    },
    t: play ? 0 : null,
    frame: play?.contact_timer ?? null,
  })

}

function describeBatterStarSwing(builder, { atBat }) {
  const batter = atBat.batter_name || 'The batter'
  const star = resolveStarAbility({
    characterName: batter, used: Boolean(atBat.star_hit_used), kind: 'swing',
  })
  if (!atBat.star_hit_used) return

  const ability = star.status === 'confirmed'
    ? star.abilityName
    : star.status === 'standard' ? 'the standard star swing' : 'a star swing'
  const pitches = atBat.pitches || []
  const hasPerPitchFlags = pitches.some((pitch) => Object.hasOwn(pitch, 'is_star_swing'))
  const starPitches = pitches.filter((pitch) => pitch.is_star_swing)
  let context = ''
  if (hasPerPitchFlags && starPitches.length) {
    const decisive = pitches.at(-1)
    if (decisive?.is_star_swing && decisive.result === 'in_play') {
      context = ' on the ball put in play'
    } else if (atBat.result === 'K' && decisive?.is_star_swing) {
      context = ' on strike three and missed'
    } else {
      const attempts = starPitches.map((pitch) => {
        const number = pitch.pitch_number_pa ?? pitches.indexOf(pitch) + 1
        const outcome = pitch.result === 'swinging_miss' ? 'missed'
          : pitch.result === 'foul' ? 'fouled off'
            : pitch.result === 'in_play' ? 'put in play' : pitch.result
        return `pitch ${number}${outcome ? ` (${outcome})` : ''}`
      }).join(', ')
      context = ` on ${attempts}; the deciding pitch was not a star swing`
    }
  }

  if (star.status === 'confirmed') {
    builder.add({
      category: 'ability',
      text: `${batter} used ${ability}${context}.`,
      status: 'observed',
      source: 'tracker log "used a star swing!" + CHARACTER_STAR_SWING',
      evidence: {
        ...star,
        star_hit_used: true,
        star_hit_connected: atBat.star_hit_connected ?? null,
        star_pitch_numbers: starPitches.map((pitch) => pitch.pitch_number_pa),
      },
    })
  } else if (star.status === 'standard') {
    builder.add({
      category: 'ability',
      text: `${batter} used ${ability}${context}, which every non-captain shares.`,
      status: 'observed',
      source: 'tracker log "used a star swing!" + CHARACTER_STAR_SWING',
      evidence: {
        ...star,
        star_hit_used: true,
        star_hit_connected: atBat.star_hit_connected ?? null,
        star_pitch_numbers: starPitches.map((pitch) => pitch.pitch_number_pa),
      },
    })
  } else if (star.status === 'unresolved') {
    builder.add({
      category: 'ability',
      text: `${batter} used ${ability}${context}. The roster does not name which swing that is.`,
      status: 'unknown',
      source: 'tracker log "used a star swing!"',
      evidence: {
        ...star,
        star_hit_used: true,
        star_hit_connected: atBat.star_hit_connected ?? null,
        star_pitch_numbers: starPitches.map((pitch) => pitch.pitch_number_pa),
      },
    })
  }
}

// --- 2-4. fielding attempt, contact, possession -----------------------------

// The fielder the game itself names as this handoff's Buddy partner, or null.
//
// A Buddy Throw carries `buddy_thrower_position` and `buddy_partner_position`
// straight from the game's own state. Action code 7 with no such throw anywhere
// on the play is a redirection the tracker cannot attribute to chemistry.
function buddyPartnerFor(play, event) {
  for (const throwRecord of play?.throws || []) {
    if (!throwRecord.buddy_throw) continue
    const pair = [throwRecord.buddy_thrower_position, throwRecord.buddy_partner_position]
    if (!pair.includes(event.by)) continue
    return pair.find((position) => position && position !== event.by) ?? null
  }
  return null
}

// A fielder knocking the ball out of the park, as opposed to a ball that
// carried out on its own. Every clause is a measurement: the game called it a
// home run, this fielder touched it with the ball ABOVE THE GROUND (a ground
// ball a fielder boots is not this), and no one ever took possession -- which
// is what rules out a ball that was deflected and then retrieved.
const DEFLECTED_OUT_MIN_HEIGHT_UNITS = 0.5

function deflectedOutOfThePark(play, event) {
  if (!play || !event) return false
  if (!(play.home_run === true || play.batted_ball_class === 'home_run')) return false
  if (event.secured === true || event.ball_contact !== 'confirmed') return false
  if (play.first_touch) return false
  const height = Number(event.ball_at?.[1])
  return Number.isFinite(height) && height > DEFLECTED_OUT_MIN_HEIGHT_UNITS
}

function describeFieldingEvent(builder, event, { play, atBat = null }) {
  const who = actorPhrase(event, atBat)
  const ability = resolveFieldingAbility({
    characterName: event.character,
    actionCode: event.action_code,
    catchType: event.catch_type ?? null,
    observedDive: event.dive === true,
    observedLeap: event.leap === true,
  })
  const base = {
    source: 'player_tracking_play.fielding_events[]',
    evidence: {
      by: event.by,
      character: event.character ?? null,
      character_id: event.character_id ?? null,
      action_code: event.action_code ?? null,
      mechanic: event.mechanic,
      fielding_attempt: event.fielding_attempt,
      ball_contact: event.ball_contact,
      secured: event.secured,
      official_error: event.official_error,
      confidence: event.confidence,
      contact_source: event.contact_source,
      distance_units: event.distance_units ?? null,
      closest_distance_units: event.closest_distance_units ?? null,
      // Three-dimensional, so it is the only one of the three that knows how
      // far above the fielder the ball was.
      closest_reach_units: event.closest_reach_units ?? null,
      within_reach: event.within_reach ?? null,
      last_contact_fielder: event.last_contact_fielder ?? null,
      fielding_contact_counter: event.fielding_contact_counter ?? null,
      // The airborne flag accompanies a LEAP and never a dive, so it stays
      // attempt context rather than a reach classifier.
      airborne_near_contact: event.airborne_near_contact ?? null,
      // How the fielder got to the ball, from the actor's own `catch_type`
      // byte. The roster resolver decides whether that observed input is an
      // ordinary dive or this character's named dive/reach ability.
      catch_type: event.catch_type ?? null,
      approach: event.approach ?? null,
      dive: event.dive === true,
      leap: event.leap === true,
      ball_landed_before_contact: event.ball_landed_before_contact ?? null,
      trajectory_turn_degrees: event.trajectory_turn_degrees ?? null,
      incoming_speed_ups: event.incoming_speed_ups ?? null,
      outgoing_speed_ups: event.outgoing_speed_ups ?? null,
    },
    t: event.t ?? null,
    frame: event.frame ?? null,
  }

  const Who = capitalized(who)
  // Rule 1: the approach to the ball is its own observation. Whether the
  // fielder dove is a different claim from whether he then held on to it.
  if (event.dive === true || event.leap === true || ability.status === 'confirmed') {
    const move = event.dive === true ? 'dove' : event.leap === true ? 'leapt' : 'went'
    builder.add({
      ...base,
      category: 'approach',
      // There is one dive/jump input, so a character mapped to Super Dive who
      // dives has used Super Dive. Saying only "dove" here understated what
      // the capture actually saw.
      text: ability.status === 'confirmed'
        ? `${Who} used ${ability.abilityName} to reach the ball.`
        : `${Who} ${move} for the ball.`,
      status: 'observed',
      source: 'player_tracking_play.fielding_events[].catch_type',
      evidence: { ...base.evidence, ability_resolution: ability },
    })
  }
  if (event.event_type === 'possession') {
    const caught = play?.caught_in_flight
    const height = Number(event.ball_height_units)
    const offGround = Number.isFinite(height) && height > 2.5
    // Taking a teammate's buddy toss is catching a throw. Describing it as
    // securing the ball "after it landed" put two fielders on one batted ball
    // and read as the tracker seeing the play twice.
    const tossedBy = event.mechanic === 'buddy_receive' ? event.received_from : null
    const tail = tossedBy
      ? ` on the buddy toss from ${positionPhrase(tossedBy)}`
      : caught
        ? ' before it landed'
        : (play?.landing ? ' after it landed' : '')
    builder.add({
      ...base,
      category: 'possession',
      text: `${Who} ${tossedBy ? 'took the ball' : 'secured the ball'}${tail}`
        + `${offGround ? `, ${feet(height)} ft off the ground` : ''}.`,
      status: 'observed',
      evidence: {
        ...base.evidence,
        caught_in_flight: caught ?? null,
        ball_height_units: Number.isFinite(height) ? height : null,
        landed_first: play?.landing ? true : false,
        received_from: tossedBy,
      },
    })
    return
  }

  // A fielding action that is not possession. Attempt, contact and outcome are
  // three separate claims and the sentence keeps them apart.
  if (event.mechanic === 'egg') {
    builder.add({
      ...base,
      category: 'mechanic',
      text: event.ball_contact === 'confirmed'
        ? `A Yoshi Egg forced ${who} to misplay the first contact.`
        : `A Yoshi Egg action fired at ${who}, and the tracker could not confirm contact.`,
      status: event.ball_contact === 'confirmed' ? 'observed' : 'unknown',
    })
    return
  }
  if (event.mechanic === 'buddy') {
    // Action code 7 does not establish a chemistry Buddy Throw, but it DOES
    // establish an intentional dive-and-toss. The fixed outgoing speed and new
    // heading show control rather than a random deflection, so this is a secure
    // followed immediately by a pass whether or not chemistry state is present.
    //
    // What the code itself is worth saying: the ball leaves at a fixed speed
    // (23.28 u/s in every occurrence measured, whatever it came in at) on a
    // new heading, so it is a deliberate redirection rather than a deflection.
    const partner = buddyPartnerFor(play, event)
    builder.add({
      ...base,
      category: 'mechanic',
      text: partner
        ? `${Who} secured and redirected the ball to ${positionPhrase(partner)} with a buddy toss during the Buddy sequence.`
        : `${Who} secured and redirected the ball to another fielder with a buddy toss.`,
      status: event.ball_contact === 'confirmed' ? 'observed' : 'unknown',
      evidence: {
        ...base.evidence,
        buddy_partner_position: partner,
        why: partner
          ? 'a Buddy Throw on this play names the chemistry partner; action 7 itself establishes the secure-and-toss'
          : 'action 7 establishes the secure-and-toss, but no Buddy state claims a chemistry pairing',
      },
    })
    return
  }
  // Mario's Fire Swing turns the ball into a fireball, and the first fielder
  // to reach it cannot hold it. Same shape as Yoshi's egg, same consequence:
  // the batter's ability made the misplay, so it is not the fielder's.
  if (event.mechanic === 'star_ball') {
    const batter = play?.batter
    const ball = batter === 'Mario' ? "Mario's fireball" : "the batter's star-swing ball"
    builder.add({
      ...base,
      category: 'mechanic',
      text: event.ball_contact === 'confirmed'
        ? `${capitalized(ball)} forced ${who} to lose the first contact.`
        : `${capitalized(ball)} action fired at ${who}, and the tracker could not confirm contact.`,
      status: event.ball_contact === 'confirmed' ? 'observed' : 'unknown',
      evidence: {
        ...base.evidence,
        batter: batter ?? null,
        action_code: event.action_code,
        why: 'action code 4 has only ever been recorded with Mario batting, and the operator names it as the Fire Swing fireball',
      },
    })
    return
  }
  if (event.mechanic === 'special_unknown') {
    builder.add({
      ...base,
      category: 'mechanic',
      text: `${Who} used an unresolved special fielding action`
        + (event.ball_contact === 'confirmed' ? ' and contacted the ball.'
          : event.ball_contact === 'missed' ? ' without contacting the ball.'
            : '; the tracker could not determine whether contact occurred.'),
      status: 'unknown',
      evidence: {
        ...base.evidence,
        ability_resolution: ability,
        unresolved_action_code: event.action_code,
      },
    })
    return
  }

  // Ordinary attempt: 2 or 3.
  if (event.ball_contact === 'confirmed') {
    builder.add({
      ...base,
      category: 'ball_contact',
      text: `${Who} contacted the ball but failed to secure it.`,
      status: 'observed',
      evidence: { ...base.evidence, ability_resolution: ability },
    })
    // THE BALL WENT OUT OFF THE FIELDER. A home run whose only contact was a
    // confirmed touch above the ground that nobody then took possession of is
    // a ball a fielder knocked over the wall -- which is the whole story of
    // the play and the reason the batter is circling. Daisy Cruiser 2026-09-04
    // PA 57 is the case: Yoshi got a glove on Red Kritter's line drive 79.8
    // units out and 1.1 units up, bounced it out of the park, and the console
    // said only that he "failed to secure it" and then, five sentences later,
    // that the plate appearance was a home run, with nothing joining the two.
    if (deflectedOutOfThePark(play, event)) {
      builder.add({
        category: 'outcome',
        text: `The ball left the park off ${who}; no fielder took possession of it, `
          + `so ${event.character || 'the fielder'} put it over the wall rather than the ball carrying out.`,
        status: 'derived',
        source: 'player_tracking_play.home_run with a confirmed elevated contact and no possession',
        evidence: {
          batted_ball_class: play?.batted_ball_class ?? null,
          home_run: play?.home_run ?? null,
          contact_height_units: event.ball_at?.[1] ?? null,
          contact_distance_units: play?.landing?.distance_units ?? null,
          first_touch: play?.first_touch ?? null,
          why: 'the ball was struck above the ground by a fielder and never came into anyone’s hands',
        },
        t: event.t ?? null,
        frame: event.frame ?? null,
      })
      // A ball that left the park has no error to determine, so stop before
      // the fallback sentence below says one is unavailable.
      return
    }
    // The physical boot and the scoring decision are different claims.
    // When the serialized PA already carries a reason this announced bobble
    // was vetoed, the outcome section below explains that ruling once. Do not
    // precede it with "no determination is available" for the same fielder.
    if (!atBat?.is_error && atBat?.error_vetoed_reason
        && atBat.fielding_events?.bobble === event.character) {
      return
    }
    //
    // On a play the batter did not survive, the second one is not open: an
    // error requires a misplay that prolonged the time at bat, prolonged the
    // life of a runner, or let a runner advance (OBR 9.12(a)(1)), and a fumble
    // the fielder recovered from in time to retire the batter did none of the
    // three. Saying "no determination is available" there states a scorer's
    // ruling as unknown when the rulebook settles it -- and it is the exact
    // question an operator asks when a bobbled ball still got the out.
    if (RETIRED_BATTER_RESULTS.has(atBat?.result)) {
      // The third limb of the rule -- "permits a runner to advance" -- is the
      // only one still open, and only when a runner actually moved. Saying so
      // is the difference between a ruling and a claim.
      const advanced = (atBat.runner_assignments || []).filter((assignment) => !assignment.isBatter
        && assignment.destination && assignment.destination !== 'out'
        && assignment.destination !== assignment.origin)
      builder.add({
        category: 'scoring',
        text: `No error is charged for that failure to secure: ${atBat.batter_name || 'the batter'} `
          + 'was still retired on the play, so it prolonged neither the time at bat nor the life of '
          + 'the batter-runner, and failing to complete a double play is not itself an error.'
          + (advanced.length
            ? ` Whether it let ${advanced.map((assignment) => assignment.runner?.characterName || 'a runner').join(' and ')}`
              + ' advance is the scorer\'s call, and the capture cannot settle it.'
            : ''),
        status: 'derived',
        source: 'OBR 9.12(a)(1) applied to plate_appearance.result',
        evidence: {
          official_error: event.official_error,
          result: atBat.result,
          rule: 'OBR 9.12(a)(1)',
          runners_advanced: advanced.map((assignment) => ({
            runner: assignment.runner?.characterName ?? null,
            origin: assignment.origin,
            destination: assignment.destination,
          })),
          why: 'an error is a misplay that prolongs the at-bat, prolongs a runner’s life, or permits an advance',
        },
      })
      return
    }
    // The at-bat may already carry the charge for this very boot. Saying "no
    // determination is available" and then "an error is charged to X" two
    // sentences later is the console contradicting itself about the same
    // event, which is exactly what the operator reads the narrative to catch.
    if (atBat?.is_error && atBat.error_kind === 'fielding'
        && atBat.error_character === event.character) {
      // AN ERROR THAT DID NOT PUT THE BATTER ON. When the ball reached the
      // ground untouched and an outfielder booted it, the batter already had
      // his base -- the hit stands and the charge is for the bases that
      // followed. Saying "the batter reached because of it" alongside a
      // recorded double is the console contradicting the result it just
      // printed.
      const keptTheHit = trackerBootLeftTheHitStanding(event)
      builder.add({
        category: 'scoring',
        text: `That failure to secure is the error charged to ${event.character}`
          + `${atBat.error_position ? ` at position ${atBat.error_position}` : ''}: the ball was `
          + 'reached with ordinary effort and not held, and '
          + (keptTheHit
            ? 'runners advanced because of it. The ball had already reached the ground '
              + 'untouched in the outfield, so the batter earned his base and keeps the hit.'
            : 'the batter reached because of it.'),
        status: 'derived',
        source: 'plate_appearance.is_error applied to the fielding event that caused it',
        evidence: {
          error_character: atBat.error_character,
          error_position: atBat.error_position ?? null,
          mechanic: event.mechanic,
          dive: event.dive ?? null,
          leap: event.leap ?? null,
          within_reach: event.within_reach ?? null,
          closest_distance_units: event.closest_distance_units ?? null,
          ball_landed_before_contact: event.ball_landed_before_contact ?? null,
          kept_the_hit: keptTheHit,
          rule: 'OBR 9.12(a)(1)',
          why: keptTheHit
            ? 'ordinary effort, confirmed contact, not secured, and the batter was already safe '
              + 'when the ball was booted -- the error is charged for the advance'
            : 'ordinary effort, confirmed contact, not secured, and the batter was safe',
        },
      })
      return
    }
    builder.add({
      category: 'scoring',
      text: 'No official error determination is available for that failure to secure.',
      status: 'not_applicable',
      source: 'player_tracking_play.fielding_events[].official_error',
      evidence: {
        official_error: event.official_error,
        why: 'the capture observes possession, not the scorer’s ruling',
      },
    })
    return
  }
  // A one-frame animation while the ball is 35 units overhead is not a play on
  // the ball, and calling it an attempt is what let a home run read as a
  // fielder who might have had it.
  if (event.within_reach === false) {
    const reach = Number(event.closest_reach_units)
    const ballHeight = Array.isArray(event.ball_at) ? Number(event.ball_at[1]) : null
    builder.add({
      ...base,
      category: 'attempt',
      text: `${Who} was in a fielding animation, but the ball never came within reach`
        + `${Number.isFinite(reach) ? ` — it stayed ${feet(reach)} ft away` : ''}`
        + `${Number.isFinite(ballHeight) && ballHeight > 5 ? `, ${feet(ballHeight)} ft overhead` : ''}.`,
      status: 'derived',
      evidence: {
        ...base.evidence,
        closest_reach_units: event.closest_reach_units ?? null,
        within_reach: false,
        why: 'no contact anywhere in the archive was made from further than 6.3 units',
      },
    })
    return
  }
  if (event.ball_contact === 'missed') {
    builder.add({
      ...base,
      category: 'attempt',
      text: `${Who} attempted to field the ball but did not make contact.`,
      status: 'observed',
      evidence: { ...base.evidence, ability_resolution: ability },
    })
    return
  }
  builder.add({
    ...base,
    category: 'attempt',
    text: `The tracker detected an attempt by ${who} but could not determine whether contact occurred.`,
    status: 'unknown',
    evidence: { ...base.evidence, ability_resolution: ability },
  })
}

