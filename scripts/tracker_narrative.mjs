// Results in which the batter-runner was retired on the batted ball. The
// complement of the safe set an error can be charged on (1B/2B/3B/ROE/FC in
// tracker_play_events.mjs); a bobble on one of these cost the defence nothing
// the rules recognise. SF and SH are absent on purpose: the batter is out, but
