// What the tracker believes happened, in plain English, derived only from
// structured facts.
//
// WHAT THIS IS FOR. During a live game there is no way to check the tracker
// except by reading numbers off a page and comparing them, in your head,
// against a play you half remember. That does not scale past an inning. A
// sentence does: "Peach hit a ground ball toward shortstop. Waluigi attempted
// to field the ball but did not make contact. Peach reached first" is either
// what happened or obviously not, and the operator knows which within a second
// of the play ending.
//
// WHAT THIS IS NOT. It is not commentary, and there is no language model
// anywhere near it. Every sentence is generated by a rule from a named field,
// and every sentence carries the field it came from. If the tracker is wrong,
// the sentence is wrong in exactly the way the data is wrong, which is the
// entire point -- a narrative that smoothed over missing data would hide the
// bug it exists to expose.
//
// THE RULES THAT KEEP IT HONEST
//
//   1. Separate facts stay separate sentences. A fielding ATTEMPT, physical
//      CONTACT with the ball, and POSSESSION of it are three different
//      observations with three different sources, and a play can have any
//      combination of them. Collapsing them into "made the play" or "missed
//      it" is what makes a tracker bug invisible.
//
//   2. Nothing is asserted more confidently than its source. A fact the game
//      declared is `observed`. A fact computed from measurements is `derived`.
//      A fact that follows from the rules of baseball rather than from a
//      measurement is `inferred`. A signal that fired without a resolvable
//      meaning is `unknown`, and it says so in the sentence.
//
//   3. A capability is never an activation. See tracker_abilities.mjs.
//
//   4. A physical boot is never an official error. The game charges errors;
//      the memory reader sees a ball not held. Those are different claims and
//      only one of them is in the data.

